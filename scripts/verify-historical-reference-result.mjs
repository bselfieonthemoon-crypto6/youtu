import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {createClient} from '@supabase/supabase-js';
assert.equal(process.env.SUPABASE_URL,'http://127.0.0.1:54421');
const db=createClient(process.env.SUPABASE_URL,process.env.SUPABASE_SERVICE_ROLE_KEY,{auth:{persistSession:false}});
const dir='artifacts/historical-reference-20260915';
const fixture=JSON.parse(await readFile(`${dir}/fixture.json`,'utf8'));
const messages=await db.from('chat_messages').select('id,role,content_blocks').eq('session_id',fixture.sessionId).eq('role','user').order('created_at');assert.ifError(messages.error);
assert.equal(messages.data.length,2);
const images=m=>(m.content_blocks??[]).filter(b=>b.type==='image');
assert.equal(images(messages.data[0]).length,1);
assert.equal(images(messages.data[1]).length,0,'Follow-up must not reattach an image');
const sourceId=images(messages.data[0])[0].assetId;
const source=await db.from('asset_objects').select('bucket,object_path').eq('id',sourceId).single();assert.ifError(source.error);
const file=await db.storage.from(source.data.bucket).download(source.data.object_path);assert.ifError(file.error);
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const originalHash=hash(Buffer.from(await file.data.arrayBuffer()));
const jobs=await db.from('background_jobs').select('id,status,payload,result').eq('session_id',fixture.sessionId);assert.ifError(jobs.error);
assert.equal(jobs.data.length,1,'Exactly one generation after follow-up');
const job=jobs.data[0];assert.equal(job.status,'succeeded');
assert.equal(job.payload.input_images.length,1);
const inputHash=hash(Buffer.from(job.payload.input_images[0].split(',')[1],'base64'));
assert.equal(inputHash,originalHash,'Provider input must be the original first-turn upload bytes');
const canvas=await db.from('canvases').select('content').eq('id',fixture.canvasId).single();assert.ifError(canvas.error);
assert(canvas.data.content.elements.some(e=>!e.isDeleted&&e.customData?.assetId===job.result.asset_id));
const report={sourceAssetId:sourceId,firstMessageId:messages.data[0].id,followupMessageId:messages.data[1].id,followupAttachmentCount:0,jobId:job.id,status:job.status,sourceBytesMatch:true,canvasInserted:true,resultAssetId:job.result.asset_id};
await writeFile(`${dir}/result.json`,JSON.stringify(report,null,2));console.log(JSON.stringify(report));
