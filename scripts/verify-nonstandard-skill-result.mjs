import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {createClient} from '@supabase/supabase-js';
assert.equal(process.env.SUPABASE_URL,'http://127.0.0.1:54421');
const sharp=createRequire(new URL('../apps/server/package.json',import.meta.url))('sharp');
const db=createClient(process.env.SUPABASE_URL,process.env.SUPABASE_SERVICE_ROLE_KEY,{auth:{persistSession:false}});
const dir='artifacts/nonstandard-image-size-20260915';
const fixture=JSON.parse(await readFile(`${dir}/fixture.json`,'utf8'));
const rows=await db.from('background_jobs').select('id,status,payload,result,error_code,error_message').eq('session_id',fixture.sessionId);assert.ifError(rows.error);
assert.equal(rows.data.length,1,'Acceptance must submit exactly one image job');
const job=rows.data[0];
const report={jobId:job.id,status:job.status,requestedRatio:job.payload.aspect_ratio,model:job.payload.model,error:job.error_message};
assert.equal(job.status,'succeeded');
const id=job.result.asset_id;
const asset=await db.from('asset_objects').select('bucket,object_path').eq('id',id).single();assert.ifError(asset.error);
const downloaded=await db.storage.from(asset.data.bucket).download(asset.data.object_path);assert.ifError(downloaded.error);
const bytes=Buffer.from(await downloaded.data.arrayBuffer());const meta=await sharp(bytes).metadata();
const error=Math.abs(meta.width/meta.height/(719/1280)-1);
const canvas=await db.from('canvases').select('content').eq('id',fixture.canvasId).single();assert.ifError(canvas.error);
assert(canvas.data.content.elements.some(e=>!e.isDeleted&&e.type==='image'&&e.customData?.assetId===id));
Object.assign(report,{assetId:id,width:meta.width,height:meta.height,ratioErrorPercent:error*100,canvasInserted:true,upstreamModel:job.result.upstream_model});
await writeFile(`${dir}/result.json`,JSON.stringify(report,null,2));
await writeFile(`${dir}/春日植物-近似尺寸.${meta.format==='jpeg'?'jpg':meta.format}`,bytes);
console.log(JSON.stringify(report));
assert(error<=.01,'Actual provider output is outside the tested near-ratio criterion');
